"""Write Hefesto's system symbol library assets/schematic/xschem_library/devices/*.sym.

openspec/changes/m8-schematic design D8 step 3 and task 7.5 (DEVLIB, clean room). The interface of every
symbol (file name, pins in order with their boxes, directions and other attributes, and the netlisting
properties) comes only from tests/data/schem/devices_interface.json, the machine-readable copy of the
"System library" interface tables of openspec/specs/schematic-symbols-and-libraries/spec.md. The graphics
are Hefesto's own simple drawings, defined in DRAWINGS below. Each file is written exactly as Hefesto's
schematic writer writes it (capability schematic-file-format, "Canonical write order"), so reading and
saving a library file gives the same bytes, and carries the Apache-2.0 notice in its `v` record.

The library sits where the PDK xschemrc files look for it: they append ${XSCHEM_SHAREDIR}/xschem_library/devices
and ${XSCHEM_SHAREDIR}/xschem_library to XSCHEM_LIBRARY_PATH, and Hefesto sets XSCHEM_SHAREDIR to
<CAD_ROOT>/assets/schematic, so a symbol resolves as both `<name>` and `devices/<name>`.

Usage:
    scripts/gen_devlib.py [--out DIR]   write the library (default assets/schematic/xschem_library/devices)
    scripts/gen_devlib.py --check       exit 1 when a committed file differs, is missing or is extra
Exit status: 0 success, 1 the library differs (--check) or a symbol has no drawing, 2 usage error.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import NamedTuple

REPO = Path(__file__).resolve().parents[1]
INTERFACE = REPO / "tests/data/schem/devices_interface.json"
OUT = REPO / "assets/schematic/xschem_library/devices"
WRITER_VERSION = "3.4.8RC"  # schematic-file-format "Writer version string" (Q-SCHEM-1)
FILE_VERSION = "1.3"  # the only version Hefesto's writer emits ("Version record and header text")
PIN_LAYER = 5
DRAW_LAYER = 4
TEXT_SIZE = 0.2

# Property-string characters that need a quoted value ("Property strings": separators, quote, escape, and
# braces, which the brace-string writer escapes).
SPECIAL = set(' \t\n";\\{}=')
SYMBOL_KEY_ORDER = ("type", "format", "lvs_format", "template", "global", "spice_ignore", "highlight")
PIN_KEY_ORDER = ("propag", "pinnumber", "verilog_type", "goto")

# The `format` of the two simulator_commands symbols, written from the interface note: the netlist text is
# LF, LF, the instance's value, LF when `sim_is_<simulator>` runs without error and returns true, and a
# single LF otherwise. Tokens end at the blank or LF that follows them ("Format string substitution").
# The escaped brace ends the @value token (schematic-netlisting "Format string
# substitution") and is written unescaped; the tcleval line gets its LF after
# the result, so the block ends with the value.
SIMULATOR_COMMANDS_FORMAT = (
    "tcleval([if {![catch {sim_is_@simulator } hefesto_sim_selected] && $hefesto_sim_selected} "
    "{return {\n\n@value\\}} else {return {}}])"
)
NOTE_PROPERTIES = {
    "simulator_commands.sym": {"format": SIMULATOR_COMMANDS_FORMAT},
    "simulator_commands_shown.sym": {"format": SIMULATOR_COMMANDS_FORMAT},
}

HEADER = (
    "* SPDX-License-Identifier: Apache-2.0\n"
    "* Copyright 2026 The Hefesto Authors\n"
    "* Hefesto system symbol library, generated by scripts/gen_devlib.py; do not edit.\n"
    "* Interface from the System library tables of schematic-symbols-and-libraries; graphics drawn for Hefesto.\n"
)


class Line(NamedTuple):
    x1: float
    y1: float
    x2: float
    y2: float
    props: str = ""
    layer: int = DRAW_LAYER


class Box(NamedTuple):
    x1: float
    y1: float
    x2: float
    y2: float
    props: str = ""
    layer: int = DRAW_LAYER


class Arc(NamedTuple):
    x: float
    y: float
    r: float
    start: float
    sweep: float
    props: str = ""
    layer: int = DRAW_LAYER


class Poly(NamedTuple):
    points: tuple[tuple[float, float], ...]
    props: str = ""
    layer: int = DRAW_LAYER


class Text(NamedTuple):
    text: str
    x: float
    y: float
    size: float = TEXT_SIZE
    props: str = ""
    rot: int = 0
    flip: int = 0


Shape = Line | Box | Arc | Poly | Text


# --- drawing helpers -------------------------------------------------------------------------------------


def poly(*points: float, props: str = "") -> Poly:
    """A polygon from a flat list of coordinates."""
    pairs = tuple((points[i], points[i + 1]) for i in range(0, len(points), 2))
    return Poly(pairs, props)


def rect(x1: float, y1: float, x2: float, y2: float) -> Poly:
    """An unfilled rectangle drawn as a closed polygon."""
    return poly(x1, y1, x2, y1, x2, y2, x1, y2, x1, y1)


def circle(x: float, y: float, r: float) -> Arc:
    return Arc(x, y, r, 0, 360)


def leads(inner: float) -> list[Shape]:
    """The vertical leads of a two-terminal symbol whose pins are at (0, -30) and (0, 30)."""
    return [Line(0, -30, 0, -inner), Line(0, inner, 0, 30)]


def labels(*texts: str, x: float = 20, y: float = -15, step: float = 15) -> list[Shape]:
    """Texts stacked downwards from (x, y)."""
    return [Text(text, x, y + i * step) for i, text in enumerate(texts)]


def plus_minus(y_plus: float, y_minus: float, x: float = 0) -> list[Shape]:
    return [Line(x - 2.5, y_plus, x + 2.5, y_plus), Line(x, y_plus - 2.5, x, y_plus + 2.5),
            Line(x - 2.5, y_minus, x + 2.5, y_minus)]


def diamond(half: float = 15) -> Poly:
    return poly(0, -half, half, 0, 0, half, -half, 0, 0, -half)


def down_arrow(y_tip: float, x: float = 0) -> list[Shape]:
    return [Line(x, -y_tip, x, y_tip), poly(x - 3.75, y_tip - 7.5, x + 3.75, y_tip - 7.5, x, y_tip,
                                            x - 3.75, y_tip - 7.5, props="fill=true")]


def code_block(x1: float, y1: float, x2: float, y2: float, caption: str, shown: str | None) -> list[Shape]:
    """A code-block frame with a caption inside and, for the `_shown` symbols, a text under it."""
    shapes: list[Shape] = [rect(x1, y1, x2, y2), Text(caption, x1 + 5, y1 + 2.5, 0.25)]
    if shown is not None:
        shapes.append(Text(shown, x1, y2 + 10, 0.25))
    return shapes


# --- drawings --------------------------------------------------------------------------------------------


def two_terminal(body: list[Shape], inner: float, *texts: str) -> list[Shape]:
    return leads(inner) + body + labels(*texts)


def resistor() -> list[Shape]:
    zigzag = poly(0, -20, 7.5, -17.5, -7.5, -12.5, 7.5, -7.5, -7.5, -2.5, 7.5, 2.5, -7.5, 7.5, 7.5, 12.5,
                  -7.5, 17.5, 0, 20)
    return two_terminal([zigzag], 20, "@name", "@value", "m=@m")


def capacitor() -> list[Shape]:
    return two_terminal([Line(-10, -2.5, 10, -2.5), Line(-10, 2.5, 10, 2.5)], 2.5, "@name", "@value", "m=@m")


def polarized_capacitor() -> list[Shape]:
    """A plain plate on the `p` side, a solid plate on the `m` side and a plus sign."""
    body: list[Shape] = [Line(0, -30, 0, -2.5), Line(-10, -2.5, 10, -2.5), Box(-10, 2.5, 10, 5, "fill=full"),
                         Line(0, 5, 0, 30), Line(-7.5, -10, -2.5, -10), Line(-5, -12.5, -5, -7.5)]
    return body + labels("@name", "@value", "m=@m")


def inductor() -> list[Shape]:
    turns: list[Shape] = [Arc(0, y, 5, 270, 180) for y in (-15, -5, 5, 15)]
