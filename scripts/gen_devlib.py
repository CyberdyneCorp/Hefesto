# --- file text -------------------------------------------------------------------------------------------


def number(value: float) -> str:
    """A floating-point field as the writer prints it (C `%.16g`, "Numeric fields")."""
    return "%.16g" % value


def brace(text: str) -> str:
    """A brace string ("Brace strings": `\\`, `{` and `}` escaped by a backslash)."""
    return "{" + text.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}") + "}"


def value_text(value: str) -> str:
    """A property value whose decoded form is `value` ("Property strings"): bare, or quoted with `"` and `\\`
    escaped."""
    if value and not (set(value) & SPECIAL):
        return value
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ordered(properties: dict[str, str], order: tuple[str, ...]) -> list[tuple[str, str]]:
    keys = [k for k in order if k in properties] + sorted(k for k in properties if k not in order)
    return [(k, properties[k]) for k in keys]


def property_string(pairs: list[tuple[str, str]], separator: str) -> str:
    return separator.join(f"{k}={value_text(v)}" for k, v in pairs)


def symbol_property(name: str, entry: dict) -> str:
    properties = {**entry["properties"], **NOTE_PROPERTIES.get(name, {})}
    return property_string(ordered(properties, SYMBOL_KEY_ORDER), "\n")


def pin_box(pin: dict) -> Box:
    pairs = [("name", pin["name"]), ("dir", pin["dir"]), *ordered(pin["properties"], PIN_KEY_ORDER)]
    x1, y1, x2, y2 = pin["box"]
    return Box(x1, y1, x2, y2, property_string(pairs, " "), PIN_LAYER)


def normal_line(line: Line) -> Line:
    """Endpoints in the order the reader stores them ("Line, box, arc and polygon records")."""
    swap = line.x2 < line.x1 or (line.x1 == line.x2 and line.y2 < line.y1)
    return line._replace(x1=line.x2, y1=line.y2, x2=line.x1, y2=line.y1) if swap else line


def normal_box(box: Box) -> Box:
    return box._replace(x1=min(box.x1, box.x2), x2=max(box.x1, box.x2), y1=min(box.y1, box.y2),
                        y2=max(box.y1, box.y2))


def by_layer(shapes: list, kind: type) -> list:
    """The shapes of one record kind, grouped by layer in creation order ("Canonical write order")."""
    return sorted((s for s in shapes if isinstance(s, kind)), key=lambda s: s.layer)


def record(shape: Shape) -> str:
    """One record in the writer's form."""
    if isinstance(shape, Line):
        line = normal_line(shape)
        return f"L {line.layer} {number(line.x1)} {number(line.y1)} {number(line.x2)} {number(line.y2)} {brace(line.props)}"
    if isinstance(shape, Box):
        box = normal_box(shape)
        return f"B {box.layer} {number(box.x1)} {number(box.y1)} {number(box.x2)} {number(box.y2)} {brace(box.props)}"
    if isinstance(shape, Arc):
        fields = " ".join(number(v) for v in (shape.x, shape.y, shape.r, shape.start, shape.sweep))
        return f"A {shape.layer} {fields} {brace(shape.props)}"
    if isinstance(shape, Poly):
        coordinates = "".join(f"{number(x)} {number(y)} " for x, y in shape.points)
        return f"P {shape.layer} {len(shape.points)} {coordinates}{brace(shape.props)}"
    size = number(shape.size)
    return (f"T {brace(shape.text)} {number(shape.x)} {number(shape.y)} {shape.rot} {shape.flip} "
            f"{size} {size} {brace(shape.props)}")


def symbol_text(name: str, entry: dict) -> str:
    """The whole `.sym` file of symbol `name`."""
    shapes: list[Shape] = list(DRAWINGS[name]) + [pin_box(pin) for pin in entry["pins"]]
    out = [
        f"v {brace(f'xschem version={WRITER_VERSION} file_version={FILE_VERSION}' + chr(10) + HEADER)}",
        "G {}",
        f"K {brace(symbol_property(name, entry))}",
        "V {}",
        "S {}",
        "F {}",
        "E {}",
    ]
    for kind in (Line, Box, Arc, Poly):
        out += [record(s) for s in by_layer(shapes, kind)]
    out += [record(s) for s in shapes if isinstance(s, Text)]
    return "\n".join(out) + "\n"


def library(interface: dict[str, dict]) -> dict[str, str]:
    """File name -> file text for every symbol of the interface."""
    missing = sorted(set(interface) - set(DRAWINGS))
    extra = sorted(set(DRAWINGS) - set(interface))
    if missing or extra:
        raise KeyError(f"drawings missing for {missing}, drawings without an interface {extra}")
    return {name: symbol_text(name, entry) for name, entry in sorted(interface.items())}


def load_interface(path: Path = INTERFACE) -> dict[str, dict]:
    return json.loads(path.read_text(encoding="utf-8"))["symbols"]


def differences(files: dict[str, str], out: Path) -> list[str]:
    """What differs between `files` and the `.sym` files in `out`."""
    present = {p.name for p in out.glob("*")} if out.is_dir() else set()
    problems = [f"extra file {name}" for name in sorted(present - set(files))]
    for name, text in files.items():
        path = out / name
        if not path.is_file():
            problems.append(f"missing {name}")
        elif path.read_bytes() != text.encode("utf-8"):
            problems.append(f"differs: {name}")
    return problems


def write(files: dict[str, str], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.sym"):
        if stale.name not in files:
            stale.unlink()
    for name, text in files.items():
        (out / name).write_bytes(text.encode("utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT, help="library folder")
    parser.add_argument("--interface", type=Path, default=INTERFACE, help="devices_interface.json")
    parser.add_argument("--check", action="store_true", help="fail when the committed library differs")
    args = parser.parse_args(argv)
    try:
        files = library(load_interface(args.interface))
    except KeyError as exc:
        print(f"gen_devlib: {exc}", file=sys.stderr)
        return 1
    if not args.check:
        write(files, args.out)
        print(f"gen_devlib: wrote {len(files)} symbols to {args.out}")
        return 0
    problems = differences(files, args.out)
    for problem in problems:
        print(f"gen_devlib: {problem} (run scripts/gen_devlib.py)", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
