"""Write the generated schematic hierarchy of the schematic benchmark (m8-schematic task 14.1).

Hefesto-authored and deterministic: the same arguments always give the same bytes. Three levels,
using only the Hefesto system library (res.sym, capa.sym, gnd.sym, ipin.sym, opin.sym, lab_pin.sym):

  stage.sch/.sym  a series resistor and a shunt capacitor to ground (ports A in, Y out)
  cell.sch/.sym   two stages in series (ports A, Y)
  top.sch         ROWS x COLS cell instances (default 100 x 100 = 10,000), each row a chain of
                  cells joined by wires, labelled IN<row> at its start and OUT<row> at its end

The hierarchical netlist of top.sch has ROWS x COLS subcircuit instance lines; the flat one has
4 x ROWS x COLS device lines.

    python3 scripts/gen_schem_hierarchy.py OUT_DIR [--rows 100] [--cols 100]

Owner: PERF (bench/schem).
"""

from __future__ import annotations

import argparse
from pathlib import Path

HEADER = "v {xschem version=3.4.8RC file_version=1.3\n* SPDX-License-Identifier: Apache-2.0\n" \
         "* Generated by scripts/gen_schem_hierarchy.py (Hefesto schematic benchmark).\n}\n"
SCHEMATIC_PROPS = "G {}\nK {}\nV {}\nS {}\nF {}\nE {}\n"

# A two-port subcircuit symbol: pins A (in) at (-40, 0) and Y (out) at (40, 0).
SYMBOL_BODY = """G {}
K {type=subcircuit
format="@name @pinlist @symname"
template="name=x1"}
V {}
S {}
F {}
E {}
L 4 -30 -20 30 -20 {}
L 4 -30 20 30 20 {}
L 4 -30 -20 -30 20 {}
L 4 30 -20 30 20 {}
L 4 -40 0 -30 0 {}
L 4 30 0 40 0 {}
B 5 -42.5 -2.5 -37.5 2.5 {name=A dir=in}
B 5 37.5 -2.5 42.5 2.5 {name=Y dir=out}
T {@symname} -25 -35 0 0 0.2 0.2 {}
T {@name} -25 25 0 0 0.2 0.2 {}
"""

STAGE = """C {ipin.sym} -100 -30 0 0 {name=p1 lab=A}
C {opin.sym} 100 30 0 0 {name=p2 lab=Y}
N -100 -30 0 -30 {}
C {res.sym} 0 0 0 0 {name=R1 value=1k m=1}
N 0 30 100 30 {}
C {capa.sym} 100 60 0 0 {name=C1 m=1 value=10f}
C {gnd.sym} 100 90 0 0 {name=l1 lab=GND}
"""

CELL = """C {ipin.sym} -200 0 0 0 {name=p1 lab=A}
C {opin.sym} 200 0 0 0 {name=p2 lab=Y}
N -200 0 -140 0 {}
C {stage.sym} -100 0 0 0 {name=x1}
N -60 0 60 0 {}
C {stage.sym} 100 0 0 0 {name=x2}
N 140 0 200 0 {}
"""

PITCH_X = 100
PITCH_Y = 200


def top_row(row: int, cols: int) -> list[str]:
    """The records of one row: its cells, the wires between them and its two labels."""
    y = row * PITCH_Y
    lines = [f"C {{lab_pin.sym}} -60 {y} 0 0 {{name=li{row} lab=IN{row}}}", f"N -60 {y} -40 {y} {{}}"]
    for col in range(cols):
        x = col * PITCH_X
        lines.append(f"C {{cell.sym}} {x} {y} 0 0 {{name=x{row * cols + col}}}")
        if col + 1 < cols:
            lines.append(f"N {x + 40} {y} {x + PITCH_X - 40} {y} {{}}")
    end = (cols - 1) * PITCH_X + 40
    lines.append(f"N {end} {y} {end + 20} {y} {{}}")
    lines.append(f"C {{lab_pin.sym}} {end + 20} {y} 0 1 {{name=lo{row} lab=OUT{row}}}")
    return lines


def top(rows: int, cols: int) -> str:
    body = [line for row in range(rows) for line in top_row(row, cols)]
    return HEADER + SCHEMATIC_PROPS + "\n".join(body) + "\n"


def files(rows: int, cols: int) -> dict[str, str]:
    """The generated files, by name."""
    return {
        "stage.sym": HEADER + SYMBOL_BODY,
        "stage.sch": HEADER + SCHEMATIC_PROPS + STAGE,
        "cell.sym": HEADER + SYMBOL_BODY,
        "cell.sch": HEADER + SCHEMATIC_PROPS + CELL,
        "top.sch": top(rows, cols),
    }


def write(out_dir: Path, rows: int, cols: int) -> Path:
    """Writes the hierarchy into `out_dir` and returns the path of top.sch."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files(rows, cols).items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    return out_dir / "top.sch"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out_dir", type=Path)
    parser.add_argument("--rows", type=int, default=100)
    parser.add_argument("--cols", type=int, default=100)
    args = parser.parse_args()
    if args.rows < 1 or args.cols < 1:
        parser.error("--rows and --cols must be at least 1")
    print(write(args.out_dir, args.rows, args.cols))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
