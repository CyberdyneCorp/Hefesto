"""Write the generated M5 golden cases (mask generation, GDS and CIF; m5-mask-gds-cif design D18).

The specs live in ``mask_cases.py`` (MASK-OS, MASK-OP, MASK-HG) and ``mask_io_cases.py``
(MASK-CI, MASK-CF, MASK-GR, MASK-GW); each module's ``NOT_AUTHORED`` lists the rows of
tests/golden/MASK/CASES.md it leaves out, with the reason and the target milestone. The
use-order probe cases MASK-UO-* have their own generator (``use_order_cases.py``).

    python3 tools/golden/authoring/m5_cases.py                # write every case
    python3 tools/golden/authoring/m5_cases.py --list         # print the case ids
    python3 tools/golden/authoring/m5_cases.py --not-authored # rows left out, and why
    python3 tools/golden/authoring/m5_cases.py --deviations   # rewrite the generated block of deviations.toml
    python3 tools/golden/authoring/m5_cases.py --dispatch     # the golden-capture.yml capture command

Never touches expected/. Until a case is captured and replays, ``deviations.toml`` lists it
as ``deferred = "M5"`` (the block between ``BEGIN`` and ``END``), so the replay stays green
(goldenlib/deviations.py: an uncaptured case may carry only a deferred entry). A workstream
whose implementation makes a case replay adds its ID to ``REPLAYED`` and re-runs
``--deviations``; an approved fix deviation goes in the hand-written part of the file.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import casegen  # noqa: E402
import mask_cases  # noqa: E402
import mask_io_cases  # noqa: E402
import tclcase  # noqa: E402

MODULES = (mask_cases, mask_io_cases)
CASES_MD = casegen.GOLDEN / "MASK" / "CASES.md"
DEVIATIONS = casegen.GOLDEN / "deviations.toml"
BEGIN = "# --- BEGIN MASK deferrals (generated by tools/golden/authoring/m5_cases.py --deviations) ---"
END = "# --- END MASK deferrals ---"
REASON = ("mask generation, GDS and CIF arrive in M5 (m5-mask-gds-cif); the case is authored before its "
          "capture in golden-capture.yml and before the owning workstream lands")
# Authored cases that replay against Magic's captured output (no deferral any more).
REPLAYED: set[str] = {"MASK-CF-022", "MASK-CI-001", "MASK-OS-001", "MASK-OS-003"}


def all_specs() -> list[tclcase.TclCase]:
    specs = [s for module in MODULES for s in module.specs()]
    ids = [s.id for s in specs]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise SystemExit(f"duplicate case ids: {duplicates}")
    return specs


def not_authored() -> dict[str, str]:
    rows: dict[str, str] = {}
    for module in MODULES:
        rows.update(module.NOT_AUTHORED)
    return rows


def inventory() -> list[str]:
    """The MASK row IDs of CASES.md's open-questions inventory (the 233 rows, not MASK-UO)."""
    text = CASES_MD.read_text(encoding="utf-8")
    return [i for i in re.findall(r"^\| (MASK-[A-Z]+-\d+) \|", text, re.MULTILINE) if not i.startswith("MASK-UO-")]


def missing_rows() -> list[str]:
    """Inventory rows neither authored nor listed in NOT_AUTHORED (an empty list once 13.4 is done)."""
    done = {s.id for s in all_specs()} | set(not_authored())
    return [i for i in inventory() if i not in done]


def output_names(spec: tclcase.TclCase) -> list[str]:
    files = [spec.output_names.get(o, o.replace("/", "__")) for o in spec.outputs]
    return ["stdout.txt", "stderr.txt", *files]


def deviation_block() -> str:
    entries = []
    for spec in all_specs():
        if spec.id in REPLAYED:
            continue
        outs = ", ".join(f'"{n}"' for n in output_names(spec))
        entries.append(f'[{spec.id}]\ndeferred = "M5"\noutputs = [{outs}]\nreason = "{REASON}"\n')
    return BEGIN + "\n\n" + "\n".join(entries) + "\n" + END + "\n"


def update_deviations(path: Path = DEVIATIONS) -> None:
    text = path.read_text(encoding="utf-8")
    block = deviation_block()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head + block + (("\n" + tail) if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def dispatch_command() -> str:
    cases = " ".join(f"tests/golden/MASK/cases/{s.id}" for s in all_specs())
    return f'gh workflow run golden-capture.yml --ref <branch> -f mode=capture -f cases="{cases}"'


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--list", action="store_true", help="print the case ids only")
    group.add_argument("--not-authored", action="store_true", help="print the rows left out and why")
    group.add_argument("--deviations", action="store_true", help="rewrite the generated block of deviations.toml")
    group.add_argument("--dispatch", action="store_true", help="print the capture dispatch command")
    args = parser.parse_args(argv)
    if args.list:
        print("\n".join(s.id for s in all_specs()))
    elif args.not_authored:
        rows = {**not_authored(), **{i: "not authored yet (task 13.4 in progress)" for i in missing_rows()}}
        for cid, why in rows.items():
            print(f"{cid}: {why}")
    elif args.deviations:
        update_deviations()
        print(DEVIATIONS.relative_to(casegen.REPO))
    elif args.dispatch:
        print(dispatch_command())
    else:
        for spec in all_specs():
            print(tclcase.write(spec).relative_to(casegen.REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
