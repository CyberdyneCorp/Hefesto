def written_specs() -> list[tclcase.TclCase]:
    """Every case this driver writes; a CAPTURE_BLOCKED case carries its blocker as capture_blocked."""
    specs = [dataclasses.replace(s, capture_blocked=BLOCKERS[s.id]) if s.id in LEFDEF_CAPTURE_BLOCKED else s
             for module in MODULES for s in module.specs()]
    ids = [s.id for s in specs]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise SystemExit(f"duplicate case ids: {duplicates}")
    return specs


def not_authored() -> dict[str, str]:
    rows: dict[str, str] = {}
    for module in LEFDEF_MODULES:
        rows.update(getattr(module, "NOT_AUTHORED", {}))
    rows.update(oasis_cases.not_authored())
    return rows


def approved_deviations() -> dict[str, str]:
    """``<id>: <decision and reason>`` of the passing cases with an approved deviation (D19)."""
    rows: dict[str, str] = {}
    for module in LEFDEF_MODULES:
        rows.update(getattr(module, "APPROVED_DEVIATIONS", {}))
    rows.update(dict(line.split(": ", 1) for line in oasis_cases.deviation_lines()))
    return rows


def inventory() -> list[str]:
    """The LEFDEF row IDs of CASES.md (``oasis_cases.not_authored()`` covers the OASIS rows itself)."""
    return list(lefdef_cases.rows())


def missing_rows() -> list[str]:
    """LEFDEF inventory rows neither authored nor listed in NOT_AUTHORED (empty once task 15.1 is done)."""
    done = {s.id for s in written_specs()} | set(not_authored())
    return [i for i in inventory() if i not in done]


def output_names(spec: tclcase.TclCase) -> list[str]:
    streams = ["stdout.txt", "stderr.txt"] if spec.streams else []
    return [*streams, *(spec.output_names.get(o, o.replace("/", "__")) for o in spec.outputs)]


def owner(spec: tclcase.TclCase) -> str:
    base = OWNERS.get(spec.capability, "its workstream")
    return f"{base} and LEFVIA" if VIA_REQUIREMENTS & set(spec.requirements) else base


def deferral_reason(spec: tclcase.TclCase) -> str:
    if spec.id in BLOCKERS:
        note = CAPTURE_BLOCKED_NOTE if spec.id in CAPTURE_BLOCKED else ""
        return f"{BLOCKER_PREFIX}{owner(spec)}; {BLOCKERS[spec.id]}{note}"
    ext = EXT_NOTE if spec.id in lefdef_cases.DEF_NET_CASES else ""
    task = TASK_154.get(spec.id) or ("15.2" if spec.area == "OASIS" else "15.1")
    return REASON.format(owner=owner(spec), task=task) + ext


def deviation_block() -> str:
    entries = []
    for spec in written_specs():
        if spec.id in REPLAYED:
            continue
        outs = ", ".join(f'"{n}"' for n in output_names(spec))
        entries.append(f'[{spec.id}]\ndeferred = "{MILESTONE}"\noutputs = [{outs}]\nreason = "{deferral_reason(spec)}"\n')
    return BEGIN + "\n\n" + "\n".join(entries) + "\n" + END + "\n"


def update_deviations(path: Path = DEVIATIONS) -> None:
    text = path.read_text(encoding="utf-8")
    block = deviation_block()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head + block + (("\n" + tail) if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def exit_blockers(path: Path = DEVIATIONS) -> list[str]:
    """``<id>: <reason>`` of every deviations.toml entry deferred to M6 (empty at the M6 exit)."""
    known = deviations.parse(path.read_text(encoding="utf-8"))
    return [f"{cid}: {d.reason}" for cid, d in sorted(known.items()) if d.deferred == MILESTONE]


def _readiness_module():
    """scripts/check_milestone_readiness.py, loaded as a module."""
    spec = importlib.util.spec_from_file_location("check_milestone_readiness", READINESS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def unresolved_decisions(milestone: str = MILESTONE) -> list[str]:
    """``<Q-ID>: ...`` of every open question an M6 capability cites without a ``Resolution:`` line."""
    readiness = _readiness_module()
    entries = readiness.load_entries()
    capabilities = readiness.milestone_assignments(readiness.ROADMAP.read_text()).get(milestone, [])
    unresolved, missing = readiness.classify_citations(capabilities, entries)
    lines = [f"{qid}: unresolved decision cited by {', '.join(caps)}" for qid, caps in unresolved.items()]
    lines += [f"{qid}: missing decision cited by {', '.join(caps)}" for qid, caps in missing.items()]
    return sorted(lines, key=lambda line: readiness.sort_key(line.split(":", 1)[0]))


def case_dir(spec: tclcase.TclCase) -> Path:
    return casegen.GOLDEN / spec.area / "cases" / spec.id


def dispatch_command(uncaptured_only: bool = False) -> str:
    """The capture dispatch; the DEF-write net cases come last (their .ext inputs are synced first)."""
    specs = [s for s in written_specs()
             if not (uncaptured_only and (case_dir(s) / "expected" / "provenance.json").is_file())]
    specs.sort(key=lambda s: s.id in lefdef_cases.DEF_NET_CASES)
    cases = " ".join(str(case_dir(s).relative_to(casegen.REPO)) for s in specs)
    return f'gh workflow run golden-capture.yml --ref <branch> -f mode=capture -f cases="{cases}"'


