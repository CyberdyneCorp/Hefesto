"""Write the generated M6 golden cases (LEF/DEF and OASIS; m6-lef-def-oasis design D19, task 15.x).

The OASIS section is ``oasis_cases.py`` (tasks 15.2, 15.6); the LEFDEF section is
``lefdef_cases.py`` (task 15.1), merged here by INTEGRATION when both land (each section keeps its
own ``specs()`` and not-authored list, so the merge only adds a module to ``SECTIONS``).

    python3 tools/golden/authoring/m6_cases.py                 # write every case
    python3 tools/golden/authoring/m6_cases.py --list          # print the case ids
    python3 tools/golden/authoring/m6_cases.py --not-authored  # rows left out, and why
    python3 tools/golden/authoring/m6_cases.py --deviations    # rewrite the generated M6 OASIS block of deviations.toml
    python3 tools/golden/authoring/m6_cases.py --dispatch      # the golden-capture.yml capture command
    python3 tools/golden/authoring/m6_cases.py --exit-check    # the M6 exit gate (task 15.6, 15.7)

``--exit-check`` lists the approved deviations recorded in case notes (OASIS-012, 030, 061 under
Q-OASIS-2; they pass, so they are not deviations.toml entries), every deviations.toml entry
deferred to M6, and every row not written yet; it fails while a deferral or an unwritten row is
left. Never touches expected/.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # goldenlib

import casegen  # noqa: E402
import oasis_cases  # noqa: E402
import tclcase  # noqa: E402
from goldenlib import deviations  # noqa: E402

DEVIATIONS = casegen.GOLDEN / "deviations.toml"

# --- OASIS section (tasks 15.2, 15.6) ------------------------------------------------------------
OASIS_BEGIN = "# --- BEGIN M6 OASIS deferrals (generated by tools/golden/authoring/m6_cases.py --deviations) ---"
OASIS_END = "# --- END M6 OASIS deferrals ---"
OASIS_REASON = ("LEF/DEF and OASIS arrive in M6 (m6-lef-def-oasis); the case is authored and captured before the "
                "owning workstream (OASFMT, OASR, OASW, OASCMD) lands")
# Captured OASIS cases that replay (no deferral any more); the owning workstream adds its cases.
OASIS_REPLAYED: set[str] = set()
# A deferral that may stay past the M6 exit names its reason here (none).
SECTIONS = (oasis_cases,)


def written_specs() -> list[tclcase.TclCase]:
    specs = [case for section in SECTIONS for case in section.specs()]
    ids = [s.id for s in specs]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise SystemExit(f"duplicate case ids: {duplicates}")
    return specs


def not_authored() -> dict[str, str]:
    rows: dict[str, str] = {}
    for section in SECTIONS:
        rows.update(section.not_authored())
    return rows


def output_names(case: tclcase.TclCase) -> list[str]:
    streams = ["stdout.txt", "stderr.txt"] if case.streams else []
    return [*streams, *(case.output_names.get(o, o.replace("/", "__")) for o in case.outputs)]


def deviation_block() -> str:
    entries = []
    for case in oasis_cases.specs():
        if case.id in OASIS_REPLAYED:
            continue
        outs = ", ".join(f'"{n}"' for n in output_names(case))
        entries.append(f'[{case.id}]\ndeferred = "M6"\noutputs = [{outs}]\nreason = "{OASIS_REASON}"\n')
    return OASIS_BEGIN + "\n\n" + "\n".join(entries) + "\n" + OASIS_END + "\n"


def update_deviations(path: Path = DEVIATIONS) -> None:
    text = path.read_text(encoding="utf-8")
    block = deviation_block()
    if OASIS_BEGIN in text:
        head, rest = text.split(OASIS_BEGIN, 1)
        tail = rest.split(OASIS_END, 1)[1].lstrip("\n")
        text = head + block + (("\n" + tail) if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def m6_deferrals(path: Path = DEVIATIONS) -> list[str]:
    known = deviations.parse(path.read_text(encoding="utf-8"))
    return [f"{cid}: {d.reason}" for cid, d in sorted(known.items()) if d.deferred == "M6"]


def exit_check() -> int:
    approved = oasis_cases.deviation_lines()
    print("approved deviations (case notes, not deviations.toml):")
    print("\n".join(f"  {line}" for line in approved))
    deferred = m6_deferrals()
    print("\n".join(deferred) if deferred else "no deferral targets M6")
    missing = [f"{row}: {why}" for row, why in not_authored().items()]
    print("\n".join(missing) if missing else "every row is written")
    return 1 if deferred or missing else 0


def dispatch_command() -> str:
    cases = " ".join(str((casegen.GOLDEN / c.area / "cases" / c.id).relative_to(casegen.REPO))
                     for c in written_specs())
    return f'gh workflow run golden-capture.yml --ref <branch> -f mode=capture -f cases="{cases}"'


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--list", action="store_true", help="print the case ids only")
    group.add_argument("--not-authored", action="store_true", help="print the rows left out and why")
    group.add_argument("--deviations", action="store_true", help="rewrite the generated M6 block of deviations.toml")
    group.add_argument("--dispatch", action="store_true", help="print the capture dispatch command")
    group.add_argument("--exit-check", action="store_true", help="the M6 exit gate; exit 1 while anything is left")
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.exit_check:
        return exit_check()
    if args.list:
        print("\n".join(s.id for s in written_specs()))
    elif args.not_authored:
        print("\n".join(f"{row}: {why}" for row, why in not_authored().items()))
    elif args.deviations:
        update_deviations()
        print(DEVIATIONS.relative_to(casegen.REPO))
    elif args.dispatch:
        print(dispatch_command())
    else:
        for case in written_specs():
            print(tclcase.write(case).relative_to(casegen.REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
