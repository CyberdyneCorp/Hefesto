"""Write the generated M6 golden cases (LEF/DEF and OASIS; m6-lef-def-oasis design D19, task 15.1).

The LEFDEF specs live in ``lefdef_lef_cases.py`` (LEFDEF-001..023, 100..142), ``lefdef_def_cases.py``
(LEFDEF-200..239, 300..335) and ``lefdef_pdk_cases.py`` (LEFDEF-240 and the library round trips
``LEFDEF-RT-<lib>`` of task 15.5), on the framework of ``lefdef_cases.py``. The OASIS specs live in
``oasis_cases.py`` (task 15.2), which this driver picks up once it exists. Each module's
``NOT_AUTHORED`` lists the rows it leaves out, with the reason and the target milestone.

    python3 tools/golden/authoring/m6_cases.py                # write every case
    python3 tools/golden/authoring/m6_cases.py --list         # print the case ids
    python3 tools/golden/authoring/m6_cases.py --not-authored # rows left out, and why
    python3 tools/golden/authoring/m6_cases.py --deviations   # rewrite the generated block of deviations.toml
    python3 tools/golden/authoring/m6_cases.py --dispatch     # the golden-capture.yml capture command
    python3 tools/golden/authoring/m6_cases.py --dispatch-uncaptured  # the same, cases without expected/
    python3 tools/golden/authoring/m6_cases.py --exit-check   # fail while a deferral targets M6 or an M6 decision is open

Never touches expected/. Until a case is captured and its workstream replays it, ``deviations.toml``
lists it as ``deferred = "M6"`` (the block between ``BEGIN`` and ``END``, every case this driver
writes), with the owning workstream in the reason, so the replay stays green (goldenlib/deviations.py:
an uncaptured case may carry only a deferred entry). A workstream whose implementation makes a case
replay adds its ID to ``REPLAYED`` and re-runs ``--deviations``; an approved fix deviation (Q-LEFDEF-1,
73, 83; task 15.7) goes in the hand-written part of the file.

The DEF-write net cases read Magic's ``.ext`` files (task 1.6): before their capture, golden-capture.yml
mode ``ext-inputs`` runs and ``lefdef_cases.py --sync-ext`` commits the files into their ``input/``.

``--exit-check`` lists every entry of ``deviations.toml`` deferred to M6, the open questions an M6
capability cites without a ``Resolution:`` line (scripts/check_milestone_readiness.py --milestone M6),
and the approved deviations the case modules record outside ``deviations.toml`` (``APPROVED_DEVIATIONS``:
cases that pass with a recorded decision, e.g. Q-OASIS-2, task 15.6). It fails while a deferral or an
open decision is left. Moving a row to a later milestone is a user decision.
"""
from __future__ import annotations

import argparse
import importlib
import importlib.util
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # goldenlib

import casegen  # noqa: E402
import lefdef_cases  # noqa: E402
import lefdef_def_cases  # noqa: E402
import lefdef_lef_cases  # noqa: E402
import lefdef_pdk_cases  # noqa: E402
import tclcase  # noqa: E402
from goldenlib import deviations  # noqa: E402

LEFDEF_MODULES = (lefdef_lef_cases, lefdef_def_cases, lefdef_pdk_cases)
OPTIONAL_MODULES = ("oasis_cases",)  # task 15.2: picked up once the module exists
DEVIATIONS = casegen.GOLDEN / "deviations.toml"
READINESS = casegen.REPO / "scripts" / "check_milestone_readiness.py"
MILESTONE = "M6"
BEGIN = "# --- BEGIN M6 deferrals (generated by tools/golden/authoring/m6_cases.py --deviations) ---"
END = "# --- END M6 deferrals ---"
# The workstream that makes a case replay (design D2), by capability; LEFVIA owns the via requirements.
OWNERS = {"lef-tech-section": "LEFTECH", "lef-read": "LEFR", "lef-write": "LEFW", "def-read": "DEFR",
          "def-write": "DEFW", "oasis-format": "OASFMT", "oasis-read": "OASR", "oasis-write": "OASW",
          "oasis-command": "OASCMD"}
VIA_REQUIREMENTS = {"LEF VIA and VIARULE definitions", "Via redefinition", "Cut growing", "Generated via geometry",
                    "Rectangle-based DEF vias", "Generated DEF vias", "Contact region identification",
                    "Generated via definitions"}
REASON = ("authored before its capture in golden-capture.yml and before {owner} makes it replay "
          "(m6-lef-def-oasis task 15.1)")
EXT_NOTE = "; its .ext inputs come from golden-capture.yml mode ext-inputs and lefdef_cases.py --sync-ext (task 1.6)"
# Captured cases that still differ from Magic: owner and cause (the M6 exit blockers).
BLOCKERS: dict[str, str] = {
}
BLOCKER_PREFIX = "M6 exit blocker, "
# Authored cases that replay against Magic's captured output (no deferral any more).
REPLAYED: set[str] = set()


def modules() -> list:
    """The case modules: the LEFDEF ones and every optional module that exists."""
    found = list(LEFDEF_MODULES)
    for name in OPTIONAL_MODULES:
        if importlib.util.find_spec(name) is not None:
            found.append(importlib.import_module(name))
    return found


def written_specs() -> list[tclcase.TclCase]:
    """Every case this driver writes."""
    specs = [s for module in modules() for s in module.specs()]
    ids = [s.id for s in specs]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise SystemExit(f"duplicate case ids: {duplicates}")
    return specs


def not_authored() -> dict[str, str]:
    rows: dict[str, str] = {}
    for module in modules():
        rows.update(getattr(module, "NOT_AUTHORED", {}))
    return rows


def approved_deviations() -> dict[str, str]:
    """``<id>: <decision and reason>`` of the passing cases with an approved deviation (D19)."""
    rows: dict[str, str] = {}
    for module in modules():
        rows.update(getattr(module, "APPROVED_DEVIATIONS", {}))
    return rows


def inventory() -> list[str]:
    """The LEFDEF row IDs of CASES.md, plus the OASIS rows once oasis_cases.py lists them (``inventory``)."""
    ids = list(lefdef_cases.rows())
    for module in modules():
        ids += list(getattr(module, "inventory", list)())
    return ids


def missing_rows() -> list[str]:
    """Inventory rows neither authored nor listed in NOT_AUTHORED (empty once task 15.1 is done)."""
    done = {s.id for s in written_specs()} | set(not_authored())
    return [i for i in inventory() if i not in done]


def output_names(spec: tclcase.TclCase) -> list[str]:
    files = [spec.output_names.get(o, o.replace("/", "__")) for o in spec.outputs]
    return ["stdout.txt", "stderr.txt", *files]


def owner(spec: tclcase.TclCase) -> str:
    base = OWNERS.get(spec.capability, "its workstream")
    return f"{base} and LEFVIA" if VIA_REQUIREMENTS & set(spec.requirements) else base


def deferral_reason(spec: tclcase.TclCase) -> str:
    if spec.id in BLOCKERS:
        return BLOCKER_PREFIX + BLOCKERS[spec.id]
    ext = EXT_NOTE if spec.id in lefdef_cases.DEF_NET_CASES else ""
    return REASON.format(owner=owner(spec)) + ext


def deviation_block() -> str:
    entries = []
    for spec in written_specs():
        if spec.id in REPLAYED:
            continue
        outs = ", ".join(f'"{n}"' for n in output_names(spec))
        entries.append(f'[{spec.id}]\ndeferred = "{MILESTONE}"\noutputs = [{outs}]\nreason = "{deferral_reason(spec)}"\n')
    return BEGIN + "\n\n" + "\n".join(entries) + "\n" + END + "\n"


def update_deviations(path: Path = DEVIATIONS) -> None:
    text = path.read_text(encoding="utf-8")
    block = deviation_block()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head + block + (("\n" + tail) if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def exit_blockers(path: Path = DEVIATIONS) -> list[str]:
    """``<id>: <reason>`` of every deviations.toml entry deferred to M6 (empty at the M6 exit)."""
    known = deviations.parse(path.read_text(encoding="utf-8"))
    return [f"{cid}: {d.reason}" for cid, d in sorted(known.items()) if d.deferred == MILESTONE]


def _readiness_module():
    """scripts/check_milestone_readiness.py, loaded as a module."""
    spec = importlib.util.spec_from_file_location("check_milestone_readiness", READINESS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def unresolved_decisions(milestone: str = MILESTONE) -> list[str]:
    """``<Q-ID>: ...`` of every open question an M6 capability cites without a ``Resolution:`` line."""
    readiness = _readiness_module()
    entries = readiness.load_entries()
    capabilities = readiness.milestone_assignments(readiness.ROADMAP.read_text()).get(milestone, [])
    unresolved, missing = readiness.classify_citations(capabilities, entries)
    lines = [f"{qid}: unresolved decision cited by {', '.join(caps)}" for qid, caps in unresolved.items()]
    lines += [f"{qid}: missing decision cited by {', '.join(caps)}" for qid, caps in missing.items()]
    return sorted(lines, key=lambda line: readiness.sort_key(line.split(":", 1)[0]))


def case_dir(spec: tclcase.TclCase) -> Path:
    return casegen.GOLDEN / spec.area / "cases" / spec.id


def dispatch_command(uncaptured_only: bool = False) -> str:
    """The capture dispatch; the DEF-write net cases come last (their .ext inputs are synced first)."""
    specs = [s for s in written_specs()
             if not (uncaptured_only and (case_dir(s) / "expected" / "provenance.json").is_file())]
    specs.sort(key=lambda s: s.id in lefdef_cases.DEF_NET_CASES)
    cases = " ".join(str(case_dir(s).relative_to(casegen.REPO)) for s in specs)
    return f'gh workflow run golden-capture.yml --ref <branch> -f mode=capture -f cases="{cases}"'


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--list", action="store_true", help="print the case ids only")
    group.add_argument("--not-authored", action="store_true", help="print the rows left out and why")
    group.add_argument("--deviations", action="store_true", help="rewrite the generated block of deviations.toml")
    group.add_argument("--dispatch", action="store_true", help="print the capture dispatch command")
    group.add_argument("--dispatch-uncaptured", action="store_true",
                       help="print the capture dispatch command of the cases without expected/")
    group.add_argument("--exit-check", action="store_true",
                       help="list the deferrals that target M6, the unresolved decisions M6 cites and the approved "
                            "deviations; exit 1 while a deferral or an open decision is left")
    return parser.parse_args(argv)


def print_not_authored() -> None:
    rows = {**not_authored(), **{i: "not authored yet (task 15.1 in progress)" for i in missing_rows()}}
    for cid, why in rows.items():
        print(f"{cid}: {why}")


def exit_check() -> int:
    blockers = exit_blockers()
    print("\n".join(blockers) if blockers else "no deferral targets M6")
    decisions = unresolved_decisions()
    print("\n".join(decisions) if decisions else "every decision M6 cites is resolved")
    for cid, why in approved_deviations().items():
        print(f"{cid}: approved deviation, {why}")
    return 1 if blockers or decisions else 0


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.exit_check:
        return exit_check()
    if args.list:
        print("\n".join(s.id for s in written_specs()))
    elif args.not_authored:
        print_not_authored()
    elif args.deviations:
        update_deviations()
        print(DEVIATIONS.relative_to(casegen.REPO))
    elif args.dispatch or args.dispatch_uncaptured:
        print(dispatch_command(args.dispatch_uncaptured))
    else:
        for spec in written_specs():
            print(tclcase.write(spec).relative_to(casegen.REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
