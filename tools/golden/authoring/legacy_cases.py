def route(start: str, dest: str, *options: str) -> str:
    """``iroute route`` from label ``start`` to label ``dest`` (the probe prints the Tcl result)."""
    return " ".join(["iroute route -slabel", start, "-dlabel", dest, *options])


def case(cid: str, capability: str, requirements: list[str], description: str, body: str, *,
         cells: dict[str, str] | None = None, outputs: tuple[str, ...] = (), extra_files: dict | None = None,
         **options) -> TclCase:
    """A scmos case: the cells (and ``extra_files``) in input/, ``load top`` when there is one, then ``body``."""
    files = {**{f"{name}.mag": text for name, text in (cells or {}).items()}, **(extra_files or {})}
    head = ["load top"] if cells and "top" in cells else []
    options.setdefault("tech", "scmos")
    return TclCase(cid, capability, requirements, description, lines(*head, body), files=files,
                   outputs=list(outputs), driver=DRIVER, golden_area=AREA, **options)


def routed(*commands: str, name: str = "routed") -> str:
    """Probes of ``commands``, then the edit cell saved as ``<name>.mag``."""
    return lines(p(*commands), p(f"save {name}"))


