def label(layer: str, rect: str, text: str, pos: int = 0) -> str:
    return f"rlabel {layer} {rect} {pos} {text}"


def mag(sections: dict[str, list[str]], labels: list[str] = (), uses: str = "", tech: str = "scmos") -> str:
    """A .mag cell: one section per type, the uses, then the labels."""
    body = "".join(f"<< {name} >>\n" + "".join(f"{record}\n" for record in records)
                   for name, records in sections.items())
    labelled = ("<< labels >>\n" + "".join(f"{text}\n" for text in labels)) if labels else ""
    return f"magic\ntech {tech}\ntimestamp 0\n{body}{uses}{labelled}<< end >>\n"


def use(cell: str, x: int, y: int, box: str) -> str:
    return f"use {cell} {cell}_0\ntimestamp 0\ntransform 1 0 {x} 0 1 {y}\nbox {box}\n"


