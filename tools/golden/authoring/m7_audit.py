def _coverage_module():
    name = "hefesto_check_requirement_coverage"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, REPO / "scripts" / "check_requirement_coverage.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def requirements() -> list[tuple[str, str, tuple[str, ...]]]:
    """(capability, requirement, classes) of every exact or behavioral M7 requirement."""
    cov = _coverage_module()
    caps = {c for group in CATALOGUES.values() for c in group}
    reqs = cov.load_requirements(REPO / "openspec" / "specs", caps, set(cov.DEFAULT_CLASSES))
    return [(r.capability, r.name, r.classes) for r in reqs]


def tagged_tests() -> dict[tuple[str, str], list[str]]:
    """(capability, requirement) -> the sources tagging it (unit-test files and case.toml paths)."""
    cov = _coverage_module()
    refs = cov.collect_tests(REPO, [REPO / "tests" / "unit", REPO / "tests" / "fuzz"], GOLDEN)
    out: dict[tuple[str, str], list[str]] = {}
    for ref in refs:
        out.setdefault((ref.capability, ref.requirement), []).append(ref.source)
    return out


def _normal(text: str) -> str:
    return re.sub(r"\(.*?\)", "", text).strip().rstrip(".").lower()


def column_cases(reqs) -> dict[tuple[str, str], set[str]]:
    """Cases whose CASES.md "requirement(s) covered" column names a requirement (a prefix of the heading counts)."""
    by_name: dict[str, list[tuple[str, str]]] = {}
    for cap, name, _ in reqs:
        by_name.setdefault(name.lower(), []).append((cap, name))
    out: dict[tuple[str, str], set[str]] = {}
    for area in CATALOGUES:
        for line in (GOLDEN / area / "CASES.md").read_text(encoding="utf-8").splitlines():
            match = ROW.match(line)
            if not match:
                continue
            case_id, row_cap, column = match.groups()
            for item in filter(None, (_normal(i) for i in column.split(";"))):
                hits = by_name.get(item) or [k for n, ks in by_name.items() if n.startswith(item) for k in ks]
                same = [k for k in hits if k[0] == row_cap]
                for key in same or hits[:1]:
                    out.setdefault(key, set()).add(case_id)
    return out


def _case_id(source: str) -> str:
    return Path(source).parent.name


def audit_rows(reqs=None, tagged=None) -> dict[str, list[list[str]]]:
    """Per catalogue, one row per requirement: capability, requirement, class, cases, unit tests, note."""
    reqs = requirements() if reqs is None else reqs
    tagged = tagged_tests() if tagged is None else tagged
    columns = column_cases(reqs)
    tables: dict[str, list[list[str]]] = {area: [] for area in CATALOGUES}
    area_of = {cap: area for area, caps in CATALOGUES.items() for cap in caps}
    for cap, name, classes in reqs:
        sources = tagged.get((cap, name), [])
        cases = {_case_id(s) for s in sources if s.startswith("tests/golden/")}
        cases |= columns.get((cap, name), set()) | set(ASSIGNED.get((cap, name), ()))
        units = sorted({s.split(":", 1)[0] for s in sources if not s.startswith("tests/golden/")})
        note = UNIT_ONLY.get((cap, name), "") if not cases else ""
        tables[area_of[cap]].append([cap, name, ", ".join(classes), ", ".join(sorted(cases)) or "-",
                                     ", ".join(units) or "-", note])
    return tables


def render(rows: list[list[str]]) -> str:
    head = ["", "## Requirement audit (m7-extraction task 17.2)", "",
            "Every exact and behavioral requirement of the catalogue's capabilities, with the golden cases that show "
            "it and the unit-test files that carry its tag. A requirement without a case states why a unit test is "
            "enough. Generated by `tools/golden/authoring/m7_cases.py --audit` (authoring/m7_audit.py).", "",
            "| Capability | Requirement | Class | Golden cases | Unit tests | Note |", "|---|---|---|---|---|---|"]
    body = ["| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |" for row in rows]
    return BEGIN + "\n" + "\n".join(head + body) + "\n\n" + END + "\n"


def write_tables(tables: dict[str, list[list[str]]] | None = None) -> list[Path]:
    tables = audit_rows() if tables is None else tables
    written = []
    for area, rows in tables.items():
        path = GOLDEN / area / "CASES.md"
        text = path.read_text(encoding="utf-8")
        block = render(rows)
        if BEGIN in text:
            head, rest = text.split(BEGIN, 1)
            text = head + block + rest.split(END, 1)[1].lstrip("\n")
        else:
            text = text.rstrip("\n") + "\n\n" + block
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def gaps(tables: dict[str, list[list[str]]]) -> list[str]:
    """Requirements with neither a case nor a unit-only reason (the audit's open rows)."""
    return [f"{row[0]}: {row[1]}" for rows in tables.values() for row in rows if row[3] == "-" and not row[5]]
