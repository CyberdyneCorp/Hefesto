"""The requirement audit of the M7 catalogues (openspec/changes/m7-extraction design D21, task 17.2).

Every `exact` and `behavioral` requirement of the 21 M7 capabilities (204, from
``scripts/check_requirement_coverage.py --milestone M7``) is listed in the audit table of the catalogue
that holds its capability's cases (EXTRACT, NETLIST or MISC ``CASES.md``), with:

* the golden cases that show it: the ``requirements`` tags of each case.toml, the "requirement(s)
  covered" column of the CASES.md rows, and the cases the audit assigned by reading the requirement
  (``ASSIGNED``: a case whose captured output shows the behaviour without naming it);
* the unit-test files that carry its ``[req:...]`` tag;
* for a requirement no case shows, why a unit test is enough (``UNIT_ONLY``): Magic's output does not
  show it (a value no command prints, a parse error path, a Hefesto-only setting).

A requirement Magic shows with no case gets a new row (EX-071 on, NL-<family>-<n+1>); the audit of
2026-11-27 added EX-071, EX-072, EX-073, NL-FLAT-19 and NL-FLAT-20. ``m7_cases.py --audit`` rewrites the
tables between ``BEGIN`` and ``END``; ``tests/test_m7_audit.py`` checks that every requirement has a row
with a case or a unit-only reason.
"""
