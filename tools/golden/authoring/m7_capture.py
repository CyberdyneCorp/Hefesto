"""Capture helpers shared by the M7 case drivers (openspec/changes/m7-extraction design D15, D21).

``M7_COLLECT``
    The ``[[collect]]`` entries of a case that extracts or netlists (goldenlib/collect.py): every
    ``.ext``, ``.spice``, ``.sim``, ``.al``, ``.nodes``, ``.res.ext``, ``.res.lump`` and ``.fh`` file
    the run writes, with the comparator design D21 assigns to it. ``*.res.ext`` comes before ``*.ext``
    (the first matching entry wins). Pass it as ``TclCase.collect``.
``ExternalCase`` / ``write_external``
    A case of the external-command mode (goldenlib/external_command.py): ``case.toml`` with
    ``[reference] mode = "external-command"`` and ``input/command.toml``; stdout, stderr and the exit
    status are compared (NL-CHK-01: Magic's ``extcheck`` on capture, ``hefesto-extcheck`` on replay).
"""
from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from casegen import GOLDEN, HEADER, _output_block, _toml_list, _toml_str  # noqa: E402
from goldenlib.collect import Collect  # noqa: E402

# The ExtTimes values are masked by magic-console itself; the saved outputs (replay --output-dir) need
# the masks too, so the console streams list them.
CONSOLE_MASKS = ["magic-stamp-note", "completed-percent", "ext-times", "magic-tech-sections"]

M7_COLLECT: tuple[Collect, ...] = (
    Collect("*.res.ext", "res-ext"),
    Collect("*.res.lump", "bytes"),
    Collect("*.ext", "ext-cap", ("ext-timestamp",)),
    Collect("*.spice", "spice-cap"),
    Collect("*.sim", "sim-cap"),
    Collect("*.al", "bytes"),
    Collect("*.nodes", "bytes"),
    Collect("*.fh", "bytes"),
)


def collect_blocks(entries: tuple[Collect, ...] | list[Collect]) -> str:
    """The ``[[collect]]`` tables of ``entries``."""
    return "".join(f"\n[[collect]]\npattern = {_toml_str(c.pattern)}\ncomparator = {_toml_str(c.comparator)}\n"
                   f"masks = {_toml_list(list(c.masks))}\n" for c in entries)


@dataclass
class ExternalCase:
    id: str
    capability: str
    requirements: list[str]
    description: str
    role: str                                        # goldenlib/external_command.py ROLES
    args: list[str] = field(default_factory=list)
    files: dict[str, str] = field(default_factory=dict)  # input/ files; the ones named in reads
    reads: list[str] = field(default_factory=list)
    driver: str = "m7_smoke_cases.py"
    notes: list[str] = field(default_factory=list)
    capture_blocked: str = ""

    @property
    def area(self) -> str:
        return self.id.split("-")[0]


def external_case_toml(case: ExternalCase) -> str:
    lines = [HEADER, "#", f"# {case.id}. Inputs only: expected/ is written by capture.py in CI (golden-capture.yml).",
             f"# Generated by tools/golden/authoring/{case.driver}. External-command mode: the program of role",
             f"# {case.role!r} runs with input/command.toml (goldenlib/external_command.py; m7-extraction D15).",
             *(f"# {n}" for n in case.notes), "",
             "schema = 1", f"id = {_toml_str(case.id)}", f"area = {_toml_str(case.area)}",
             f"capability = {_toml_str(case.capability)}", f"requirements = {_toml_list(case.requirements)}",
             'tool = "magic"', f"description = {_toml_str(case.description)}",
             *([f"capture_blocked = {_toml_str(case.capture_blocked)}"] if case.capture_blocked else []), "",
             "[reference]", 'mode = "external-command"']
    text = "\n".join(lines) + "\n"
    text += _output_block("stdout.txt", "stdout", "bytes", ["extcheck-memory"])
    text += _output_block("stderr.txt", "stderr", "bytes", ["prog-name"])
    text += _output_block("exitcode.txt", "exitcode", "bytes", [])
    return text


def command_toml(case: ExternalCase) -> str:
    return (f"{HEADER}\nschema = 1\nrole = {_toml_str(case.role)}\nargs = {_toml_list(case.args)}\n"
            f"reads = {_toml_list(case.reads)}\n")


def write_external(case: ExternalCase, golden: Path = GOLDEN) -> Path:
    root = golden / case.area / "cases" / case.id
    inp = root / "input"
    inp.mkdir(parents=True, exist_ok=True)
    (root / "case.toml").write_text(external_case_toml(case), encoding="utf-8")
    (inp / "command.toml").write_text(command_toml(case), encoding="utf-8")
    for name, content in case.files.items():
        (inp / name).write_text(content, encoding="utf-8", newline="")
    return root
