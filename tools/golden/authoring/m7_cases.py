"""Write the M7 golden cases (openspec/changes/m7-extraction design D21, tasks 2.5, 2.6 and 17).

R1 authors the 44 NETLIST rows with hand-written ``.ext`` inputs (``netlist_cases.py``: NL-FLAT-01..18,
NL-SPICE-01..14, NL-HIER-01..06, NL-SIM-01..05, NL-CHK-01) and the 53 flat EX rows (``extract_cases.py``
with ``exttest.tech``: EX-001..042, 044..046, 048, 057..063). The rest of the M7 catalogue comes later:
the other 17 EX rows (task 17.1), NL-RES and NL-RESNET and MISC-ANT (task 17.3), the PDK cases (task
17.4), LEFDEF-336 (task 17.6). SCRIPT-API-16 and SCRIPT-API-20 exist; their ``deferred = "M7"``
entries go when they replay (task 17.5).

    python3 tools/golden/authoring/m7_cases.py                 # write the cases (never expected/)
    python3 tools/golden/authoring/m7_cases.py --list          # the authored case ids
    python3 tools/golden/authoring/m7_cases.py --not-authored  # catalogue rows without a case: reason and task
    python3 tools/golden/authoring/m7_cases.py --deviations    # rewrite the M7 block of deviations.toml
    python3 tools/golden/authoring/m7_cases.py --dispatch      # the golden-capture.yml capture command
    python3 tools/golden/authoring/m7_cases.py --exit-check    # task 17.7 / design D25: fails while work is left

Until a case is captured and its workstream replays it, ``deviations.toml`` lists it as
``deferred = "M7"`` in the block between ``BEGIN`` and ``END``, with every output (a deferred entry may
name a case whose capture is pending). A workstream whose implementation makes a case replay adds its
ID to ``REPLAYED`` and re-runs ``--deviations``.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import casegen  # noqa: E402
import extract_cases  # noqa: E402
import netlist_cases  # noqa: E402
import tclcase  # noqa: E402
from goldenlib import deviations  # noqa: E402

MILESTONE = "M7"
DEVIATIONS = casegen.GOLDEN / "deviations.toml"
BEGIN = "# --- BEGIN M7 deferrals (generated by tools/golden/authoring/m7_cases.py --deviations) ---"
END = "# --- END M7 deferrals ---"
OWNER = {"EX": "the EXTRACT workstreams through EXTCMD's driver (m7-extraction tasks 4-9; replay from R3)",
         "NL-FLAT": "EXTFLAT (m7-extraction task 10)", "NL-SPICE": "SPICE (m7-extraction task 11)",
         "NL-HIER": "SPICE (m7-extraction task 11.6)", "NL-SIM": "SIM (m7-extraction task 12)",
         "NL-CHK": "SIM (m7-extraction task 12.4)"}
PDK_LIBS = ("sky130_fd_sc_hd", "gf180mcu_fd_sc_mcu7t5v0", "sg13g2_stdcell")
LATER = {**extract_cases.LATER, **netlist_cases.LATER,
         **{f"MISC-ANT-{n:02d}": "ANTENNA (task 17.3, R3)" for n in range(1, 10)},
         **{f"{area}-PDK-{lib}": "PDK standard cells (task 17.4, R5)" for area in ("EXTRACT", "NETLIST") for lib in PDK_LIBS},
         "LEFDEF-336": "extract all then def write on LEFDEF-317's layout (task 17.6)"}
EXISTING = ("SCRIPT-API-16", "SCRIPT-API-20")  # deferred to M7 by earlier milestones (task 17.5)
CATALOGUE_TOTAL = 155  # design D21

# Case IDs whose replay passes; each leaves the generated deferral block.
REPLAYED: set[str] = set()

# The decisions a deferred case already carries (design D21: a case whose expected output holds a Magic
# behaviour that an approved fix changes names the decision).
DECISIONS: dict[str, list[str]] = {"EX-024": ["Q-EXTRACT-6"], netlist_cases.CHK_ID: netlist_cases.CHK_DECISIONS}

# Cases whose expected/ is hand-derived instead of captured, with the approved decision that allows it
# (design R7 option (a), m7-decision-table M7-9): capture.py never runs them, --exit-check lists them.
HAND_DERIVED: dict[str, str] = {netlist_cases.CHK_ID: netlist_cases.CHK_HAND_DERIVED}


def tcl_cases() -> list[tclcase.TclCase]:
    return [*extract_cases.cases(), *netlist_cases.cases()]


def authored_ids() -> list[str]:
    return sorted([c.id for c in tcl_cases()] + [netlist_cases.CHK_ID])


def catalogue_rows() -> list[str]:
    """Every M7 row: the EXTRACT and NETLIST catalogues, MISC-ANT, the PDK cases, the SCRIPT and LEFDEF cases."""
    rows = []
    for area, pattern in (("EXTRACT", r"EX-\d{3}"), ("NETLIST", r"NL-[A-Z]+-\d{2}"), ("MISC", r"MISC-ANT-\d{2}")):
        text = (casegen.GOLDEN / area / "CASES.md").read_text(encoding="utf-8")
        rows += re.findall(rf"^\| ({pattern}) \|", text, re.MULTILINE)
    rows += [f"{area}-PDK-{lib}" for area in ("EXTRACT", "NETLIST") for lib in PDK_LIBS]
    return rows + list(EXISTING) + ["LEFDEF-336"]


def case_dir(case_id: str) -> Path:
    area = "EXTRACT" if case_id.startswith("EX-") else "NETLIST" if case_id.startswith("NL-") else case_id.split("-")[0]
    return casegen.GOLDEN / area / "cases" / case_id


def not_authored() -> dict[str, str]:
    return {row: LATER.get(row, "not authored yet") for row in catalogue_rows() if not (case_dir(row) / "case.toml").is_file()}


def output_names(case_id: str) -> list[str]:
    if case_id == netlist_cases.CHK_ID:
        return netlist_cases.extcheck_outputs()
    case = next(c for c in tcl_cases() if c.id == case_id)
    collected = ["collected/*"] if case.collect else []
    return ["stdout.txt", "stderr.txt", *(case.output_names.get(o, o.replace("/", "__")) for o in case.outputs),
            *collected]


def owner(case_id: str) -> str:
    return OWNER["EX" if case_id.startswith("EX-") else case_id.rsplit("-", 1)[0]]


def deviation_block() -> str:
    entries = []
    for case_id in authored_ids():
        if case_id in REPLAYED:
            continue
        outs = ", ".join(f'"{name}"' for name in output_names(case_id))
        reason = f"captured in R1 (m7-extraction tasks 2.5, 2.6); replays once {owner(case_id)} lands"
        if case_id in HAND_DERIVED:
            reason = f"expected/ hand-derived (design R7 option (a), M7-9); replays once {owner(case_id)} lands"
        decisions = f"decisions = {casegen._toml_list(DECISIONS[case_id])}\n" if case_id in DECISIONS else ""
        entries.append(f'[{case_id}]\n{decisions}deferred = "{MILESTONE}"\noutputs = [{outs}]\nreason = "{reason}"\n')
    return BEGIN + "\n\n" + "\n".join(entries) + "\n" + END + "\n"


def update_deviations(path: Path = DEVIATIONS) -> None:
    text = path.read_text(encoding="utf-8")
    block = deviation_block()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head + block + (("\n" + tail) if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def dispatch_command(only_uncaptured: bool = False) -> str:
    dirs = [case_dir(i) for i in authored_ids() if i not in HAND_DERIVED]
    if only_uncaptured:
        dirs = [d for d in dirs if not (d / "expected" / "provenance.json").is_file()]
    cases = " ".join(str(d.relative_to(casegen.REPO)) for d in dirs)
    return f'gh workflow run golden-capture.yml --ref <branch> -f mode=capture -f cases="{cases}"'


def m7_deferrals() -> list[str]:
    return sorted(i for i, dev in deviations.load(casegen.GOLDEN).items() if dev.deferred == MILESTONE)


def exit_check() -> int:
    """Design D25: every catalogue row authored, no M7 deferral left (the approved deviations of
    task 17.7 carry decisions, not deferrals). A hand-derived case is listed with its decision and
    does not count as work left."""
    rows, missing, deferred = catalogue_rows(), not_authored(), m7_deferrals()
    print(f"M7 catalogue: {len(rows)} cases (design D21: {CATALOGUE_TOTAL})")
    for case_id, reason in HAND_DERIVED.items():
        print(f"hand-derived: {case_id} ({', '.join(DECISIONS.get(case_id, []))}): {reason}")
    for row, reason in missing.items():
        print(f"not authored: {row}: {reason}")
    for case_id in deferred:
        print(f"deferred: {case_id}")
    ok = len(rows) == CATALOGUE_TOTAL and not missing and not deferred
    print("exit check: " + ("clean" if ok else "work left"))
    return 0 if ok else 1


def write_all() -> None:
    for case in tcl_cases():
        print(tclcase.write(case).relative_to(casegen.REPO))
    print(netlist_cases.write_extcheck(casegen.GOLDEN).relative_to(casegen.REPO))


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--list", action="store_true", help="print the authored case ids")
    action.add_argument("--not-authored", action="store_true", help="catalogue rows without a case")
    action.add_argument("--deviations", action="store_true", help="rewrite the M7 block of deviations.toml")
    action.add_argument("--dispatch", action="store_true", help="print the golden-capture.yml dispatch")
    action.add_argument("--dispatch-uncaptured", action="store_true", help="the dispatch for cases without expected/")
    action.add_argument("--exit-check", action="store_true", help="fail while an M7 row or deferral is left")
    args = parser.parse_args(argv)
    if args.list:
        print("\n".join(authored_ids()))
    elif args.not_authored:
        print("\n".join(f"{row}: {reason}" for row, reason in not_authored().items()))
    elif args.deviations:
        update_deviations()
    elif args.dispatch or args.dispatch_uncaptured:
        print(dispatch_command(args.dispatch_uncaptured))
    elif args.exit_check:
        return exit_check()
    else:
        write_all()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
