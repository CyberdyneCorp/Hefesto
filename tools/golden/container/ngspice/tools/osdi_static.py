"""Built-in OSDI modules for libngspice-hefesto (task 5.2, patch 0001).

OpenVAF-reloaded compiles a Verilog-A file into object files, links them into
one shared `.osdi` and deletes the objects. Every module exports the same
names (OSDI_DESCRIPTORS, OSDI_VERSION_MAJOR, osdi_log, ...), so several
modules cannot be linked into one library as they are. This tool:

  compile    runs OpenVAF with a linker shim first on PATH (OpenVAF starts the
             linker by name: `clang` on macOS, `ld` elsewhere), which copies
             the objects OpenVAF passes to it before the real linker runs;
             renames the module's exported OSDI symbols with the per-module
             prefix `hefesto_osdi_<module>_` (llvm-objcopy --redefine-sym on
             each object), merges the objects into one relocatable object
             (`ld -r`) in which only the renamed symbols stay global, and
             writes <out>/<module>.o, <module>.symbols and <module>.json;
  registry   writes hefesto_osdi_builtins.c: the HefestoOsdiModule table of
             hefesto_static.h, one entry per <module>.symbols of a directory
             (an empty table without one);
  link-wrapper  the shim itself (internal).

The modules' licences are listed in MODULE_LICENCES; ngspice_manifest.py puts
them in ngspice-manifest.json (THIRD_PARTY_NOTICES.md has the rows).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PREFIX = "hefesto_osdi_"
# Names an OSDI 0.4 library exports (OpenVAF's osdi crate): the OSDI_* tables
# and values, and the osdi_log hook ngspice sets.
EXPORTED = re.compile(r"^(OSDI_[A-Z0-9_]+|osdi_log)$")
MODULE_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
# OpenVAF names its objects <dst>.o and <dst>.o<n> (osdi::compile).
OBJECT_ARG = re.compile(r"\.o[0-9a-z]*$")
ENV_CAPTURE = "HEFESTO_OSDI_CAPTURE"
ENV_REAL = "HEFESTO_OSDI_REAL_LINKER"

# The sg13g2 set of simulation-engine-embedding "OSDI compact models", with the
# licence each source states (IHP-Open-PDK at the ihp-ngspice pin).
MODULE_LICENCES = {
    "psp103": "LicenseRef-PSP103 (NXP Semiconductors, CEA-Leti, Delft University of Technology, "
              "Arizona State University; copyright notice in psp103.va, no licence text)",
    "psp103_nqs": "LicenseRef-PSP103 (as psp103)",
    "r3_cmc": "Apache-2.0 AND ECL-2.0 (IHP Open PDK Authors; R3_CMC by the Si2 Compact Model Coalition)",
    "mosvar": "LicenseRef-ASU-Si2-mosvar (Arizona State University, Freescale, Si2; permissive with conditions)",
    "cap_cmomi": "Apache-2.0 (IHP PDK Authors)",
    "cap_cmomf": "Apache-2.0 (IHP PDK Authors)",
}


# --- names ------------------------------------------------------------------------------

def c_name(symbol: str, macho: bool) -> str:
    """The C name of an object-file symbol (Mach-O adds a leading underscore)."""
    return symbol[1:] if macho and symbol.startswith("_") else symbol


def object_name(name: str, macho: bool) -> str:
    return "_" + name if macho else name


def prefixed(module: str, name: str) -> str:
    return f"{PREFIX}{module}_{name}"


def exported_names(symbols: list[str], macho: bool) -> list[str]:
    """The C names of the OSDI exports among defined global object symbols, sorted."""
    return sorted({c_name(s, macho) for s in symbols if EXPORTED.match(c_name(s, macho))})


def object_args(argv: list[str]) -> list[str]:
    """The arguments of a linker command line that are OpenVAF's object files."""
    return [a for a in argv if OBJECT_ARG.search(a) and os.path.isfile(a)]


def is_macho(path: Path) -> bool:
    magic = path.read_bytes()[:4]
    return magic in (b"\xcf\xfa\xed\xfe", b"\xce\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xfe\xed\xfa\xce")


# --- registry ---------------------------------------------------------------------------

def read_symbols(path: Path) -> list[tuple[str, str]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            original, renamed = line.split()
            rows.append((original, renamed))
    return rows


def registry_source(modules: dict[str, list[tuple[str, str]]]) -> str:
    """hefesto_osdi_builtins.c for `modules` (name -> [(OSDI name, renamed C name)])."""
    out = ["/* GENERATED by third_party/ngspice/tools/osdi_static.py; do not edit.",
           " * SPDX-License-Identifier: Apache-2.0",
           " * Copyright 2026 The Hefesto Authors",
           " *",
           " * The OSDI modules compiled into libngspice-hefesto (Hefesto patch 0001),",
           " * each with its exports renamed hefesto_osdi_<module>_<name>. */",
           '#include "hefesto_static.h"', ""]
    if not modules:
        out += ["const HefestoOsdiModule hefesto_osdi_modules[1] = {{0, 0, 0}};",
                "const size_t hefesto_osdi_module_count = 0;", ""]
        return "\n".join(out)
    for module, rows in modules.items():
        out += [f"extern char {renamed};" for _, renamed in rows]
        out.append(f"static const HefestoOsdiSymbol {module}_symbols[{len(rows)}] = {{")
        out += [f'    {{"{original}", &{renamed}}},' for original, renamed in rows]
        out += ["};", ""]
    out.append(f"const HefestoOsdiModule hefesto_osdi_modules[{len(modules)}] = {{")
    out += [f'    {{"{m}", {m}_symbols, {len(rows)}}},' for m, rows in modules.items()]
    out += ["};", f"const size_t hefesto_osdi_module_count = {len(modules)};", ""]
    return "\n".join(out)


def write_registry(directory: Path | None, out: Path) -> None:
    modules = {}
    if directory is not None:
        for path in sorted(directory.glob("*.symbols")):
            modules[path.stem] = read_symbols(path)
    text = registry_source(modules)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")


# --- compile ----------------------------------------------------------------------------

def run(argv: list[str], **kwargs) -> None:
    proc = subprocess.run(argv, capture_output=True, text=True, check=False, **kwargs)
    if proc.returncode != 0:
        raise SystemExit(f"osdi_static: {' '.join(argv)} failed ({proc.returncode}):\n{proc.stdout}{proc.stderr}")


def write_shim(directory: Path) -> None:
    """`ld` and `clang` that run this tool's link-wrapper."""
    body = f'#!/bin/sh\nexec "{sys.executable}" -I "{Path(__file__).resolve()}" link-wrapper "$@"\n'
    for name in ("ld", "clang"):
        shim = directory / name
        shim.write_text(body, encoding="utf-8")
        shim.chmod(0o755)


def run_openvaf(args, capture: Path) -> list[Path]:
    """Runs OpenVAF on the source with the shim and returns the objects it linked."""
    shim = capture / "bin"
    shim.mkdir()
    write_shim(shim)
    real = shutil.which("clang" if sys.platform == "darwin" else "ld")
    if real is None:
        raise SystemExit("osdi_static: the linker OpenVAF calls is not on PATH")
    env = dict(os.environ, PATH=f"{shim}{os.pathsep}{os.environ.get('PATH', '')}")
    env[ENV_CAPTURE], env[ENV_REAL] = str(capture / "objects"), real
    (capture / "objects").mkdir()
    source = args.source.resolve()
    # OpenVAF runs in the source's directory (its `include` paths are relative).
    openvaf = str(args.openvaf.resolve()) if os.sep in str(args.openvaf) else str(args.openvaf)
    run([openvaf, *args.openvaf_arg, source.name, "-o", str(capture / f"{args.module}.osdi")],
        cwd=source.parent, env=env)
    objects = sorted((capture / "objects").iterdir())
    if not objects:
        raise SystemExit("osdi_static: OpenVAF passed no object file to the linker")
    return objects


def defined_globals(nm: str, objects: list[Path]) -> list[str]:
    proc = subprocess.run([nm, "--defined-only", "--extern-only", "--format=just-symbols", *map(str, objects)],
                          capture_output=True, text=True, check=True)
    return [line.strip() for line in proc.stdout.splitlines() if line.strip() and not line.endswith(":")]


def relocate(args, objects: list[Path], work: Path) -> list[tuple[str, str]]:
    """Renames the exports in every object, merges them, and keeps only the renamed ones global."""
    macho = is_macho(objects[0])
    names = exported_names(defined_globals(args.nm, objects), macho)
    rows = [(n, prefixed(args.module, n)) for n in names]
    redefine = [f"--redefine-sym={object_name(o, macho)}={object_name(r, macho)}" for o, r in rows]
    renamed = []
    for i, obj in enumerate(objects):
        target = work / f"renamed{i}.o"
        run([args.objcopy, *redefine, str(obj), str(target)])
        renamed.append(str(target))
    out = args.out_dir / f"{args.module}.o"
    keep = [object_name(r, macho) for _, r in rows]
    if macho:
        exported = [a for name in keep for a in ("-exported_symbol", name)]
        run([args.ld, "-r", "-o", str(out), *renamed, *exported])
    else:
        merged = work / "merged.o"
        run([args.ld, "-r", "-o", str(merged), *renamed])
        run([args.objcopy, *[f"--keep-global-symbol={k}" for k in keep], str(merged), str(out)])
    return rows


def compile_module(args) -> None:
    if not MODULE_NAME.match(args.module):
        raise SystemExit(f"osdi_static: module name {args.module!r} is not [a-z][a-z0-9_]*")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="osdi-") as tmp:
        work = Path(tmp)
        rows = relocate(args, run_openvaf(args, work), work)
    if not any(o == "OSDI_DESCRIPTORS" for o, _ in rows):
        raise SystemExit(f"osdi_static: {args.module} exports no OSDI_DESCRIPTORS")
    (args.out_dir / f"{args.module}.symbols").write_text("".join(f"{o} {r}\n" for o, r in rows), encoding="utf-8")
    meta = {"module": args.module, "source": args.source.name,
            "source_sha256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
            "license": MODULE_LICENCES.get(args.module, "unknown"),
            "compiler": args.compiler_id, "symbols": [r for _, r in rows]}
    (args.out_dir / f"{args.module}.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")


# --- link-wrapper -----------------------------------------------------------------------

def link_wrapper(argv: list[str]) -> int:
    capture = Path(os.environ[ENV_CAPTURE])
    first = len(list(capture.iterdir()))
    for i, path in enumerate(object_args(argv)):
        shutil.copyfile(path, capture / f"{first + i:03d}-{Path(path).name}.o")
    return subprocess.run([os.environ[ENV_REAL], *argv], check=False).returncode


# --- command line ------------------------------------------------------------------------

def parse_args(argv: list[str]):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="command", required=True)
    c = sub.add_parser("compile")
    c.add_argument("--openvaf", type=Path, required=True)
    c.add_argument("--openvaf-arg", action="append", default=[])
    c.add_argument("--source", type=Path, required=True)
    c.add_argument("--module", required=True)
    c.add_argument("--out-dir", type=Path, required=True)
    c.add_argument("--objcopy", default="llvm-objcopy")
    c.add_argument("--nm", default="llvm-nm")
    c.add_argument("--ld", default="ld")
    c.add_argument("--compiler-id", default="OpenVAF-reloaded")
    r = sub.add_parser("registry")
    r.add_argument("--dir", type=Path)
    r.add_argument("--out", type=Path, required=True)
    return ap.parse_args(argv)


def main(argv: list[str]) -> int:
    if argv and argv[0] == "link-wrapper":
        return link_wrapper(argv[1:])
    args = parse_args(argv)
    if args.command == "compile":
        compile_module(args)
    else:
        write_registry(args.dir, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
