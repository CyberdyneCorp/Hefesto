std::optional<std::uint32_t> keysym_from_name(std::string_view name) noexcept {
  const auto it = std::find_if(kKeysyms.begin(), kKeysyms.end(), [&](const KeysymName& k) { return k.name == name; });
  if (it == kKeysyms.end()) {
    return std::nullopt;
  }
  return it->keysym & 0xFFFFU;
}

std::string_view keysym_name(std::uint32_t keysym) noexcept {
  const auto it =
      std::find_if(kKeysyms.begin(), kKeysyms.end(), [&](const KeysymName& k) { return k.keysym == keysym; });
  return it == kKeysyms.end() ? std::string_view{} : it->name;
}

