"""Compile the canvas shaders to SPIR-V and embed them as a C++ header.

The generated header (src/generated/rect_spv.hpp) is committed, so building
Hefesto never needs a shader compiler. Run this script after editing a shader:

    python3 src/render/vulkan/shaders/compile_shaders.py [--glslang PATH]

or build the CMake target `hefesto_render_shaders` (defined when
glslangValidator is found).
"""

from __future__ import annotations

import argparse
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parent / "src" / "generated" / "rect_spv.hpp"
SHADERS = (("rect.vert", "kRectVertSpv"), ("rect.frag", "kRectFragSpv"))

HEADER = """\
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 The Hefesto Authors
//
// GENERATED by src/render/vulkan/shaders/compile_shaders.py from
// {sources}. Do not edit; edit the shaders and re-run the script.

#pragma once

#include <cstdint>

namespace hefesto::render::spv {{
"""


def compile_spirv(glslang: str, source: Path, out_dir: Path) -> list[int]:
    target = out_dir / (source.name + ".spv")
    subprocess.run(
        [glslang, "-V", "--target-env", "vulkan1.0", "-o", str(target), str(source)],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    data = target.read_bytes()
    if len(data) % 4 != 0:
        raise ValueError(f"{target}: SPIR-V size is not a multiple of 4")
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def format_array(name: str, words: list[int]) -> str:
    lines = [f"inline constexpr std::uint32_t {name}[] = {{"]
    for i in range(0, len(words), 6):
        chunk = ", ".join(f"0x{w:08x}u" for w in words[i : i + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--glslang", default=shutil.which("glslangValidator"))
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    if not args.glslang:
        print("compile_shaders: glslangValidator not found", file=sys.stderr)
        return 1

    parts = [HEADER.format(sources=", ".join(s for s, _ in SHADERS))]
    with tempfile.TemporaryDirectory() as tmp:
        for source, name in SHADERS:
            words = compile_spirv(args.glslang, HERE / source, Path(tmp))
            parts.append(format_array(name, words) + "\n")
    parts.append("}  // namespace hefesto::render::spv\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
